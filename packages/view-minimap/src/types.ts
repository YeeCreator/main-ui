import type { Vec2, WorldRect } from '@main-ui/core/rendering';

/**
 * 缩略导航（`Minimap`）的公共类型。
 *
 * ## 一个抽象，两种画法
 *
 * 「小地图」（游戏）与「缩略图 / 导航」（画布）在坐标数学上完全一致，
 * 差别只有**简化画法**。这里用一个 `kind` 字段表达这个差别：
 *
 * - `point`：实体画成一个质点（游戏里的单位、城市）
 * - `rect`：单元画成一个框（画布里的节点、卡片）
 * - `path`：折线（路线、连线）
 *
 * 判据上是统一的：**点就是零宽高的矩形**。宿主不必在两套 API 之间挑，
 * 传同一种结构即可；缺省时组件按 `width` / `height` 是否为 0 自动判。
 */

/** 缩略图内一项内容的简化画法。 */
export type MinimapItemKind = 'point' | 'rect' | 'path';

/**
 * 缩略图的**外框形状**。
 *
 * 为什么不总是方形：缩略图是「世界的缩小映射」，它的外框应当与世界本身的
 * 轮廓一致。世界是矩形范围时方形正确；世界是圆形时，方形外框会在四角
 * 凭空造出「那里也有内容」的错觉 —— 使用者据此导航过去，发现是空的。
 *
 * 形状只影响**可视裁切与边框**，不影响坐标映射（映射恒按世界范围等比适配）。
 */
export type MinimapShape = 'rect' | 'circle';

/**
 * 坐标指示器（缩略图上的三维坐标轴）。
 *
 * 为什么需要：缩略图只画出「有个框」，使用者无法判断**视角朝哪**。
 * 三维档尤其如此 —— 相机一转，画面全变，而缩略图看起来没动，
 * 于是「不知道转到哪里了」。
 *
 * ## 两种画法
 *
 * - **给了 `axes`**（推荐，三维档）：画出**投影后的三根立体箭头**，
 *   按业界惯例 **X 红 / Y 绿 / Z 蓝**（与 UE、Blender、Maya 的 gizmo 一致）。
 *   三根轴的长度差与方向差自然表达出相机倾角 —— 一眼看出「我在俯视还是侧看」。
 * - **只给 `azimuth`**（二维档）：只画一条指北线。二维平面没有纵深，
 *   画三维轴是虚张声势。
 *
 * 箭头按**正交投影**压到平面：只取每个轴在「屏幕右/上」方向上的分量，
 * 不做透视缩短（小地图是示意，不是渲染）。
 */
export type MinimapCompass = {
  /**
   * 相机方位角（弧度）。无 `axes` 时用它画指北线：
   * `0` 时北朝上，正值逆时针。
   */
  azimuth: number;
  /**
   * 屏幕空间的世界轴向量（可选）。给了就画**立体三色箭头**，忽略指北线。
   *
   * 三个向量应当是「世界 X/Y/Z 轴投影到屏幕后的二维方向与长度」，
   * 长度已含该轴对屏幕的可见程度（正交投影下即 `|dot(axis, screenPlane)|`）。
   * 宿主从相机基向量算出来传入（MUI 不知道相机存在哪）。
   */
  axes?: {
    /** 世界 +X 轴在屏幕上的投影（右为正、下为正）。 */
    x: { x: number; y: number };
    /** 世界 +Y 轴在屏幕上的投影。 */
    y: { x: number; y: number };
    /** 世界 +Z 轴在屏幕上的投影。 */
    z: { x: number; y: number };
  };
  /** 是否同时画出世界坐标轴（**已废弃**，等价于给 `axes`；保留仅为兼容旧宿主）。 */
  showAxes?: boolean;
};

/** 缩略图内的一项内容（世界坐标）。 */
export type MinimapItem = {
  /** 稳定标识（用于渲染 key）。 */
  id: string;
  /**
   * 该项在世界中的范围。
   *
   * `point` 型忽略宽高（可传 0）；`path` 型用 `points`，此字段仅用于包围盒。
   */
  world: WorldRect;
  /**
   * 简化画法。缺省按 `world.width === 0 && world.height === 0` 自动判为 `point`。
   */
  kind?: MinimapItemKind;
  /**
   * `path` 型的折线点（世界坐标）。
   *
   * 与 `world` 二选一：`path` 必须给 `points`，`world` 仍建议给包围盒，
   * 否则该项不参与「内容范围」计算，可能被画到缩略图外。
   */
  points?: Vec2[];
  /** 语义分组（供宿主在插槽里按组着色，组件本身不含业务语义）。 */
  group?: string;
  /** 是否高亮（例如已选中、当前所在区域）。 */
  highlighted?: boolean;
};

/** 视口矩形在缩略图内的绘制结果（供自定义插槽使用）。 */
export type MinimapViewportFrame = {
  /** 绘制矩形（像素，已含最小可见尺寸）。 */
  frame: WorldRect;
  /** 真实矩形（像素，未撑开；点击/命中判定应用它）。 */
  raw: WorldRect;
};
